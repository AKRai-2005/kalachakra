"""Experiment 18 — the world model was trained past its useful point.

How we got here
---------------
Experiment 16 ran experiment 14's configuration on experiment 14's folds and
caught 4 of 12, not 1 of 12. A deterministic control in the same run - gradient
boosting, which has no training randomness - reproduced experiment 14's row to
the digit, so the data, labels, features, folds and scoring were provably the
same. Experiment 17 then ruled out the obvious suspect: six seeds, and the world
model caught 4 of 12 every single time, with zero variance.

That leaves training length. Experiment 14's script takes `--epochs` with a
default of 12 and **never recorded which value produced the published row**.
Experiment 15's grid began at 25 epochs, described them as "experiment 01's
settings", and its baseline arm scored AUC 0.677 catching 1 of 12 - which is
experiment 14's published row to within noise. So the published number was
almost certainly measured at 25 epochs while the script's default says 12.

This experiment settles it by sweeping the epoch count directly.

Two things are at stake, and the second is the interesting one
---------------------------------------------------------------
**A reproducibility defect.** If a published row cannot be regenerated by
running the script that claims to produce it, the number is not reproducible,
whatever its value. That is a real fault in this repository and it is being
fixed rather than explained away.

**A finding about the model.** 12 epochs catches 4 of 12; 25 epochs catches 1
of 12. If that is a curve rather than two accidents, the world model *overfits
with training*, and experiment 15 - which searched 25, 40, 40, 40 epochs and
concluded that tuning does not help - searched the wrong end of the axis
entirely. Its conclusion would then be right by luck and wrong by method.

There is also a metric question underneath. At 12 epochs the world model caught
4 of 12 with a **worse** AUC (0.30) than at 25 epochs, where it caught 1 of 12
with AUC 0.66. If that holds across the sweep then AUC and detection-at-an-
operating-point move in opposite directions here, and every AUC in this project
is measuring something other than what a defender buys.

PRE-REGISTERED PREDICTIONS  (written before the first run, unedited since)

  P1  Some epoch count in the grid reproduces experiment 14's published row -
      1 of 12 caught, AUC near 0.66. If none does, that row cannot be produced
      by this code at any training length and must be withdrawn rather than
      corrected.

  P2  Detection count falls as training lengthens. The 4-of-12 at 12 epochs and
      1-of-12 at 25 epochs are two points on a declining curve, not two
      unrelated results.

  P3  AUC rises as training lengthens, moving opposite to detection count. If
      the two moved together the choice of metric would not matter; the claim
      is that here it decides the answer.

  P4  Gradient boosting's 7 of 12 is not beaten at any training length. The
      correction changes the size of the gap, not who is ahead.

  P5  The best epoch count in this sweep is below 25 - that is, outside
      experiment 15's grid entirely, which began at 25 and only went up.

Run:  python experiments/exp18_ctu13_epochs.py        (~50 min)
"""

from __future__ import annotations

import json
import pickle
import sys
import time
from pathlib import Path

import numpy as np
import torch
from sklearn.metrics import roc_auc_score
from xgboost import XGBClassifier

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments"))

from exp01_leadtime import (  # noqa: E402
    HORIZON, build_dataset, flat_features, to_scores, train_world_model,
)
from exp14_ctu13_leadtime import MAX_FPR, N_HOSTS, wm_scores  # noqa: E402

from kalachakra.dynamics.world_model import TrainConfig  # noqa: E402
from kalachakra.metrics.leadtime import lead_at_fpr  # noqa: E402
from kalachakra.state.graph import GraphBuilder  # noqa: E402

RESULTS = ROOT / "results"
CACHE = RESULTS / "ctu13_episodes_full.pkl"

EPOCH_GRID = (6, 12, 18, 25, 40)
# Two seeds, because experiment 17 established seed-invariance only at 12
# epochs. A longer run has more opportunity to diverge, and a conclusion about
# overfitting must not rest on a single draw at the long end.
SEEDS = (0, 1)

EXP14_WM_CAUGHT = 1
EXP14_WM_AUC = 0.6634
EXP14_GBDT_CAUGHT = 7


def op(scores) -> dict:
    o = lead_at_fpr(scores, MAX_FPR)
    n = sum(1 for e in scores if e.compromise_window is not None)
    return {"caught": int(round(o["detection_rate"] * n)), "n_attack": n,
            "mean_lead": float(o["mean_lead"]), "fpr": float(o["achieved_fpr"])}


def main() -> int:
    t0 = time.time()
    print("=" * 78)
    print("KALACHAKRA  ·  Experiment 18  ·  Training length on CTU-13")
    print("=" * 78)

    if not CACHE.exists():
        print(f"\n{CACHE} not found. Run experiment 14 first.")
        return 2
    with CACHE.open("rb") as fh:
        groups = pickle.load(fh)
    scenarios = sorted(groups, key=lambda s: int(s.split("-")[0]))
    builder = GraphBuilder([f"n{i}" for i in range(N_HOSTS)])
    folds = [s for s in scenarios
             if any(e.is_attack and e.compromise_window for e in groups[s])]

    print(f"\n      {len(folds)} scored folds, horizon {HORIZON}")
    print(f"      epochs: {', '.join(str(e) for e in EPOCH_GRID)}")
    print(f"      seeds:  {', '.join(str(s) for s in SEEDS)}")
    print("      everything except the epoch count is experiment 14's setup")

    cache = {}
    for held in folds:
        tr_eps = [e for s in scenarios if s != held for e in groups[s]]
        te_eps = groups[held]
        cache[held] = (build_dataset(tr_eps, builder), build_dataset(te_eps, builder),
                       flat_features(tr_eps, builder), flat_features(te_eps, builder))

    # Deterministic reference, computed once: gradient boosting does not depend
    # on the world model's epoch count, so it is the fixed line everything else
    # is read against.
    gb_scored, gb_auc = [], []
    for held in folds:
        (_, _, _, _, Ytr, _), (_, _, _, _, Yte, mte), Ftr, Fte = cache[held]
        gb = XGBClassifier(n_estimators=120, max_depth=4, learning_rate=0.1,
                           subsample=0.9, eval_metric="logloss",
                           verbosity=0, n_jobs=4)
        gb.fit(Ftr.reshape(-1, Ftr.shape[-1]), Ytr.reshape(-1))
        pg = gb.predict_proba(Fte.reshape(-1, Fte.shape[-1]))[:, 1].reshape(Yte.shape)
        gb_scored.extend(to_scores(mte, pg))
        yte = Yte.reshape(-1)
        if len(np.unique(yte)) > 1:
            gb_auc.append(roc_auc_score(yte, pg.reshape(-1)))
    gb_op = op(gb_scored)
    gb_op["auc"] = float(np.mean(gb_auc))
    ctrl = gb_op["caught"] == EXP14_GBDT_CAUGHT
    print(f"\n      control: gradient boosting {gb_op['caught']}/"
          f"{gb_op['n_attack']} caught, lead {gb_op['mean_lead']:.2f}, "
          f"AUC {gb_op['auc']:.3f} -> {'PASS' if ctrl else 'FAIL'}")

    print(f"\n      {'epochs':>6s} {'seed':>5s} | {'caught':>8s} {'lead':>7s} "
          f"{'FPR':>6s} {'AUC':>6s}")
    rows = []
    for ep in EPOCH_GRID:
        for seed in SEEDS:
            torch.manual_seed(seed)
            np.random.seed(seed)
            scored, aucs = [], []
            for held in folds:
                (Xtr, Atr, Gtr, Str, _, _), (Xte, Ate, Gte, _, Yte, mte), _, _ = \
                    cache[held]
                wm = train_world_model(Xtr, Atr, Gtr, Str,
                                       TrainConfig(epochs=ep, lr=2e-3),
                                       verbose=False)
                p = wm_scores(wm, Xte, Ate, Gte)
                scored.extend(to_scores(mte, p))
                yte = Yte.reshape(-1)
                if len(np.unique(yte)) > 1:
                    aucs.append(roc_auc_score(yte, p.reshape(-1)))
            o = op(scored)
            o["auc"] = float(np.mean(aucs))
            o.update(epochs=ep, seed=seed)
            rows.append(o)
            print(f"      {ep:6d} {seed:5d} | {o['caught']:4d}/{o['n_attack']:<3d} "
                  f"{o['mean_lead']:7.2f} {o['fpr']:6.3f} {o['auc']:6.3f}",
                  flush=True)

    # Averaged over seeds, which is what the trend claims are about.
    by_ep = {ep: {"caught": float(np.mean([r["caught"] for r in rows
                                           if r["epochs"] == ep])),
                  "auc": float(np.mean([r["auc"] for r in rows
                                        if r["epochs"] == ep])),
                  "mean_lead": float(np.mean([r["mean_lead"] for r in rows
                                              if r["epochs"] == ep]))}
             for ep in EPOCH_GRID}

    print(f"\n      {'epochs':>6s} {'caught':>8s} {'lead':>7s} {'AUC':>6s}   "
          f"(mean over seeds)")
    for ep in EPOCH_GRID:
        b = by_ep[ep]
        print(f"      {ep:6d} {b['caught']:8.1f} {b['mean_lead']:7.2f} "
              f"{b['auc']:6.3f}")

    eps = np.array(EPOCH_GRID, dtype=float)
    caught_curve = np.array([by_ep[e]["caught"] for e in EPOCH_GRID])
    auc_curve = np.array([by_ep[e]["auc"] for e in EPOCH_GRID])
    r_caught = float(np.corrcoef(eps, caught_curve)[0, 1]) \
        if caught_curve.std() > 0 else float("nan")
    r_auc = float(np.corrcoef(eps, auc_curve)[0, 1]) \
        if auc_curve.std() > 0 else float("nan")
    best_ep = max(EPOCH_GRID, key=lambda e: (by_ep[e]["caught"],
                                             by_ep[e]["mean_lead"]))

    # Which setting, if any, regenerates the published row.
    repro = [r for r in rows
             if r["caught"] == EXP14_WM_CAUGHT and abs(r["auc"] - EXP14_WM_AUC) < 0.10]

    print(f"\n      epochs vs detections   r = {r_caught:+.3f}")
    print(f"      epochs vs AUC          r = {r_auc:+.3f}")
    print(f"      best epoch count       {best_ep} "
          f"({by_ep[best_ep]['caught']:.1f} of {rows[0]['n_attack']} caught)")
    if repro:
        s = ", ".join(f"{r['epochs']}ep/seed{r['seed']} (AUC {r['auc']:.3f})"
                      for r in repro)
        print(f"      reproduces exp 14 row  {s}")
    else:
        print("      reproduces exp 14 row  NOTHING IN THIS GRID DOES")

    verdicts = {
        "P1": bool(repro),
        "P2": bool(r_caught < 0),
        "P3": bool(r_auc > 0),
        "P4": max(by_ep[e]["caught"] for e in EPOCH_GRID) < EXP14_GBDT_CAUGHT,
        "P5": best_ep < 25,
    }
    detail = {
        "P1": (f"reproduced at {repro[0]['epochs']} epochs" if repro
               else "no setting in the grid reproduces 1 of 12 at AUC ~0.66"),
        "P2": f"epochs vs detections r = {r_caught:+.3f} "
              f"({caught_curve[0]:.1f} at {EPOCH_GRID[0]} -> "
              f"{caught_curve[-1]:.1f} at {EPOCH_GRID[-1]})",
        "P3": f"epochs vs AUC r = {r_auc:+.3f} "
              f"({auc_curve[0]:.3f} -> {auc_curve[-1]:.3f})",
        "P4": f"best world model {max(by_ep[e]['caught'] for e in EPOCH_GRID):.1f} "
              f"vs gradient boosting {EXP14_GBDT_CAUGHT}",
        "P5": f"best epoch count {best_ep}; experiment 15's grid started at 25",
    }
    print("\n" + "=" * 78)
    print("PRE-REGISTERED PREDICTIONS")
    print("=" * 78)
    for k in ("P1", "P2", "P3", "P4", "P5"):
        print(f"  {k}  {'HOLDS ' if verdicts[k] else 'FAILS '}  {detail[k]}")

    payload = {
        "question": "experiment 14's published world-model row could not be "
                    "regenerated; is training length the reason?",
        "horizon": HORIZON,
        "epoch_grid": list(EPOCH_GRID),
        "seeds": list(SEEDS),
        "gbdt_control": {**gb_op, "matches_exp14": bool(ctrl)},
        "rows": rows,
        "by_epochs": by_ep,
        "trend": {"epochs_vs_detections_r": r_caught, "epochs_vs_auc_r": r_auc,
                  "best_epochs": best_ep},
        "reproduces_exp14": [{"epochs": r["epochs"], "seed": r["seed"],
                              "auc": r["auc"]} for r in repro],
        "published": {"exp14_wm_caught": EXP14_WM_CAUGHT,
                      "exp14_wm_auc": EXP14_WM_AUC,
                      "exp14_gbdt_caught": EXP14_GBDT_CAUGHT},
        "verdicts": verdicts,
        "detail": detail,
    }
    (RESULTS / "exp18_verdicts.json").write_text(json.dumps(payload, indent=1))
    print("\n  wrote results/exp18_verdicts.json")
    print(f"  total {time.time() - t0:.0f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
